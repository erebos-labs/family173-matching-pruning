"""Offline replay using only local scripts and a temporary regeneration directory."""
import argparse
from pathlib import Path
import shlex
import subprocess
import sys
import tempfile


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--skip-manifest', action='store_true', help='pre-packaging preflight only')
    args = parser.parse_args()
    def run(*parts):
        command = [sys.executable, '-B', *(['-O'] if sys.flags.optimize else []), *map(str, parts)]
        print('$', shlex.join(command), flush=True)
        subprocess.run(command, cwd=root, check=True)
    if not args.skip_manifest:
        run(root / 'src/check_manifest.py')
    run(root / 'src/verify.py', *sorted((root / 'fixtures').glob('*.json')))
    run(root / 'src/bounded_checks.py', 'primitive')
    run(root / 'src/bounded_checks.py', 'covers')
    run(root / 'src/check_obstructions.py')
    run(root / 'src/test_rejections.py')
    run(root / 'tests/release_regressions.py')
    with tempfile.TemporaryDirectory(prefix='f173-cover-replay-') as temporary:
        temp = Path(temporary)
        run(root / 'src/make_fixtures.py', temp / 'fixtures')
        expected = sorted(p.name for p in (root / 'fixtures').glob('*.json'))
        actual = sorted(p.name for p in (temp / 'fixtures').glob('*.json'))
        if expected != actual:
            raise ValueError('regeneration inventory mismatch')
        for name in expected:
            if (root / 'fixtures' / name).read_bytes() != (temp / 'fixtures' / name).read_bytes():
                raise ValueError('regenerated fixture differs: ' + name)
        print('PASS all nine fixture files regenerated byte-for-byte.', flush=True)
        result = temp / 'converted.json'
        run(root / 'src/convert.py', root / 'examples/repeated-H-request.json', result)
        run(root / 'src/verify.py', result)
    print('PASS complete offline replay. No inherited file was rewritten.')


if __name__ == '__main__':
    main()
